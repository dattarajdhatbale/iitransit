"""Final scene frames = approved layouts + car-v3 (students seated) + the three standing students.
Standing students sit at their start positions and start hidden: the final frame is the end of the story.
Run: python3 -I build_final.py   (reads frame-desktop-v3-full-route.svg, frame-mobile-v4-tall.svg)"""
import re
STAND_K = 1.3   # standing students are drawn 1.3x the car's units

def group_span(s, start):
    depth, i = 0, start
    while True:
        o = s.find('<g', i); c = s.find('</g>', i)
        if o != -1 and o < c: depth += 1; i = o + 2
        else:
            depth -= 1; i = c + 4
            if depth == 0: return start, i

def students_markup():
    st = open('students-v1.svg').read()
    out = {}
    for n in (1, 2, 3):
        a, z = group_span(st, st.index(f'<g id="stand-{n}">'))
        out[n] = st[a:z]
    return out

def compose(src, dst, car_scale, starts, mirror):
    f = open(src).read()
    car = open('car-v3.svg').read()
    defs_clip = car[car.index('<clipPath'):car.index('</clipPath>') + len('</clipPath>')]
    va, vz = group_span(car, car.index('<g id="vehicle">'))
    vehicle_inner = car[car.index('>', va) + 1: vz - 4].replace(defs_clip, '').strip()
    fa, fz = group_span(f, f.index('<g id="vehicle"'))
    head = f[fa:f.index('>', fa) + 1]                       # keep the frame's own vehicle transform
    S = students_markup(); s = car_scale * STAND_K
    stands = '\n'.join(
        f'      <g id="stand-{n}-place" transform="translate({x},{y}) scale({-s if mirror else s},{s})">{S[n]}</g>'
        for n, (x, y) in zip((1, 2, 3), starts))
    students = f'''<!-- ============ STANDING STUDENTS (start positions; hidden in the final frame) ============ -->
    <g id="students" opacity="0">
{stands}
    </g>
'''
    f = f[:fa] + students + '    ' + head + '\n      ' + vehicle_inner + '\n    </g>' + f[fz:]
    f = f.replace('  <defs>', '  <defs>\n    ' + defs_clip.replace('\n', ' '), 1)
    f = f.replace('<!-- Generated by build_frames.py', '<!-- Generated by build_final.py')
    open(dst, 'w').write(f)
    print('wrote', dst)

compose('frame-desktop-v3-full-route.svg', '../final/iit-transit-final-frame-desktop.svg', 1.15,
        [(140, 828), (262, 830), (405, 828)], mirror=False)
compose('frame-mobile-v4-tall.svg', '../final/iit-transit-final-frame-mobile.svg', 1.2,
        [(455, 326), (575, 326), (695, 326)], mirror=True)
