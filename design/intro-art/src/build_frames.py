import re

def inner_of_root_group(path):
    s = open(path).read()
    a = s.index('<g stroke-linecap="round" stroke-linejoin="round">')
    a = s.index('>', a) + 1
    z = s.rindex('</g>')
    return s[a:z].strip('\n')

def car_inner(path):
    s = open(path).read()
    a = s.index('<g id="vehicle">'); a = s.index('>', a) + 1
    z = s.rindex('</g>', 0, s.rindex('</g>'))   # close of #vehicle (root group closes last)
    return s[a:z].strip('\n')

def indent(block, n):
    pad = ' ' * n
    return '\n'.join(pad + l.strip() if l.strip() else '' for l in block.split('\n'))

def block_from(frame, gid):
    """Copy one top-level group (side-decor, start-point, destination-pin) verbatim from a v1 frame."""
    s = open(frame).read()
    a = s.index(f'<g id="{gid}"')
    depth, i = 0, a
    while True:
        o = s.find('<g', i); c = s.find('</g>', i)
        if o != -1 and o < c: depth += 1; i = o + 2
        else:
            depth -= 1; i = c + 4
            if depth == 0: return s[a:i]

