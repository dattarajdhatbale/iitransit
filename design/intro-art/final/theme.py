"""Theme the IITransit art: hard-coded colours -> roles (CSS classes + custom properties).
Outputs, per input SVG:
  themed/<name>.svg        classes + an embedded <style> (light by default, dark under prefers-color-scheme
                           or a .dark-mode / .it-dark ancestor). For standalone use and previews.
  themed/<name>.app.svg    classes only, no <style>: for inlining into the React app, which loads iitransit-art.css
  iitransit-art.css        the app stylesheet: light on .it-art, dark under html.dark-mode (the app's own toggle)
Run: python3 -I theme.py"""
import re, os, sys

ROLES = {  # hex -> (role, light, dark)
 '#1E1A4D': ('ink',      '#1E1A4D', '#E4DCFA'),   # outlines
 '#F1EDFA': ('wall',     '#F1EDFA', '#1F2944'),
 '#F5F2F9': ('wall-hi',  '#F5F2F9', '#263152'),
 '#E7DFF5': ('ledge',    '#E7DFF5', '#2E3A5E'),
 '#E1D8F2': ('recess',   '#E1D8F2', '#232D4C'),
 '#E7E1F6': ('glass',    '#E7E1F6', '#2B3557'),
 '#F7F5FC': ('tyre',     '#F7F5FC', '#18203A'),
 '#DDD2F0': ('hub',      '#DDD2F0', '#3B4670'),
 '#D9CBF1': ('skin',     '#D9CBF1', '#B3A1E0'),
 '#C6B4E6': ('window',   '#C6B4E6', '#7A63B5'),
 '#AA82BC': ('accent',   '#AA82BC', '#A98ADF'),
 '#5A3D7A': ('deep',     '#5A3D7A', '#15122E'),
 '#B7A6CD': ('muted',    '#B7A6CD', '#4E5880'),
 '#C7BBD9': ('shadow',   '#C7BBD9', '#05070F'),
 '#E9E1F6': ('slab',     '#E9E1F6', '#19213A'),
 '#BFB2D4': ('bush',     '#BFB2D4', '#4E5880'),
 '#DCD2EA': ('trail',    '#DCD2EA', '#252F50'),
 '#CDB5DE': ('flag',     '#CDB5DE', '#8F70C6'),
 '#C0A9D8': ('spark',    '#C0A9D8', '#5A4C8C'),
 '#F0913F': ('signal',   '#F0913F', '#F0913F'),
}
EXTRA = {  # roles that only exist through context
 'feature': ('#1E1A4D', '#1E1A4D'),   # eyes, brows, mouths: stay dark on light skin
 'hair':    ('#1E1A4D', '#7058B4'),
 'cloth':   ('#1E1A4D', '#15122E'),   # dark shorts stay dark
}
BY_ROLE = {r: (l, d) for _, (r, l, d) in ROLES.items()} | EXTRA

def to_classes(svg):
    def repl(m):
        tag = m.group(0)
        if tag.startswith('</') or tag.startswith('<!') or tag.startswith('<?'): return tag
        cls = []
        def take(attr, prefix):
            nonlocal tag
            mm = re.search(rf'\s{attr}="(#[0-9A-Fa-f]{{6}})"', tag)
            if mm:
                hexv = mm.group(1).upper()
                if hexv not in ROLES: sys.exit(f'unmapped colour {hexv}')
                cls.append(prefix + ROLES[hexv][0]); tag = tag.replace(mm.group(0), '')
        take('fill', 'f-'); take('stroke', 's-')
        if not cls: return tag
        if ' class="' in tag: tag = tag.replace(' class="', ' class="' + ' '.join(cls) + ' ', 1)
        else: tag = re.sub(r'^<([\w:]+)', lambda t: f'<{t.group(1)} class="{" ".join(cls)}"', tag)
        return tag
    out = re.sub(r'<[^>]+>', repl, svg)
    out = re.sub(r'<svg ', '<svg class="it-art" ', out, count=1) if 'class="it-art"' not in out else out
    return out

def css_vars(which):
    i = 0 if which == 'light' else 1
    return ';'.join(f'--it-{r}:{v[i]}' for r, v in BY_ROLE.items())

def css_rules(scope='.it-art'):
    rules = []
    for r in BY_ROLE:
        rules.append(f'{scope} .f-{r}{{fill:var(--it-{r})}}{scope} .s-{r}{{stroke:var(--it-{r})}}')
    rules.append(f'{scope} .face .f-ink{{fill:var(--it-feature)}}{scope} .face .s-ink{{stroke:var(--it-feature)}}')
    rules.append(f'{scope} .hair .f-ink{{fill:var(--it-hair)}}{scope} .hair .s-ink{{stroke:var(--it-hair)}}')
    rules.append(f'{scope} .shorts.f-ink{{fill:var(--it-cloth)}}')
    return ''.join(rules)

EMBED = (f'<style>.it-art{{{css_vars("light")}}}'
         f'@media (prefers-color-scheme:dark){{.it-art:not(.it-light){{{css_vars("dark")}}}}}'
         f'.dark-mode .it-art,.it-art.it-dark{{{css_vars("dark")}}}'
         f'{css_rules()}</style>')

APP_CSS = f'''/* IITransit intro art theme. Generated by theme.py; edit the palette there.
   Light values on .it-art; dark values follow the app's own toggle (html.dark-mode). */
.it-art{{{css_vars("light")}}}
.dark-mode .it-art{{{css_vars("dark")}}}
{css_rules()}
'''

def resolve(svg, which):
    """Bake a theme into plain hex colours (for PNG previews and link-preview images)."""
    i = 0 if which == 'light' else 1
    stack = []
    def repl(m):
        tag = m.group(0)
        if tag.startswith('</g'):
            if stack: stack.pop()
            return tag
        if tag.startswith('<g') and not tag.endswith('/>'):
            c = re.search(r'class="([^"]*)"', tag); stack.append(c.group(1).split() if c else [])
        ctx = {k for s in stack for k in s}
        own = re.search(r'class="([^"]*)"', tag); own = set(own.group(1).split()) if own and not tag.startswith('<g') else set()
        def sub(attr):
            nonlocal tag
            mm = re.search(rf'\s{attr}="(#[0-9A-Fa-f]{{6}})"', tag)
            if not mm: return
            role = ROLES[mm.group(1).upper()][0]
            if role == 'ink' and attr == 'fill' and 'shorts' in own: role = 'cloth'
            elif role == 'ink' and 'face' in ctx: role = 'feature'
            elif role == 'ink' and 'hair' in ctx: role = 'hair'
            tag = tag.replace(mm.group(0), f' {attr}="{BY_ROLE[role][i]}"')
        sub('fill'); sub('stroke')
        return tag
    return re.sub(r'<[^>]+>', repl, svg)

