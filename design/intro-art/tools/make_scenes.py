"""Generate the React scene components and their geometry from the approved, themed art.

Inputs  (relative to design/intro-art/):
  final/themed/iit-transit-final-frame-desktop.app.svg
  final/themed/iit-transit-final-frame-mobile.app.svg
Outputs (relative to the repo root):
  src/landing/scenes/DesktopScene.tsx
  src/landing/scenes/MobileScene.tsx
  src/landing/scenes/sceneGeometry.ts

The art stays the single source of truth: change the SVGs (and re-run theme.py), then re-run this.
Never edit the generated files by hand.

Run from the repo root:  python3 design/intro-art/tools/make_scenes.py
"""
import os
import re
import sys

ART = os.path.join("design", "intro-art", "final", "themed")
OUT = os.path.join("src", "landing", "scenes")

# Story geometry that is not in the SVGs themselves (from the Intro Animation Script).
# Fractions are distances along the route path, as a share of its length.
STORY = {
    "desktop": {"pickup": 0.183, "stop": 0.702, "startFacing": 1,
                "captionBox": (60, 80, 840, 340)},   # x, y, width, height in scene units
    "mobile": {"pickup": 0.16, "stop": 0.779, "startFacing": -1, "captionBox": None},
}
CAR_ANCHOR = (153, 134)     # axle point in the car's own units
STUDENT_SCALE_K = 1.3       # standing students are drawn 1.3x the car's units

GENERATED_HEADER = "// GENERATED by design/intro-art/tools/make_scenes.py from the approved art. Do not edit by hand.\n"

ATTR_RENAMES = {"class": "className", "xlink:href": None, "xmlns:xlink": None, "xmlns": None}
ROOT_ONLY_DROPS = {"width", "height"}   # the root <svg> is sized by CSS; every other element keeps them


def camel(name):
    if name.startswith(("aria-", "data-")):
        return name
    parts = name.split("-")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def tidy_numbers(value):
    # 1.4949999999999999 -> 1.495 (float noise from the art scripts)
    return re.sub(r"-?\d+\.\d{6,}", lambda m: f"{float(m.group(0)):.4f}".rstrip("0").rstrip("."), value)


def svg_to_jsx(svg, root_extra):
    svg = re.sub(r"<\?xml[^>]*\?>", "", svg).strip()

    def comment(m):
        text = m.group(1).replace("*/", "* /").strip()
        return "{/* " + text + " */}"

    svg = re.sub(r"<!--\s*Generated by.*?-->", "", svg, flags=re.S)   # stale build notes from the art scripts
    svg = re.sub(r"<!--(.*?)-->", comment, svg, flags=re.S)

    def tag(m):
        whole = m.group(0)
        if whole.startswith("</") or whole.startswith("{/*"):
            return whole
        name_m = re.match(r"<([\w:]+)", whole)
        tag_name = name_m.group(1)
        self_close = whole.rstrip().endswith("/>")
        attrs = re.findall(r'([\w:-]+)="([^"]*)"', whole)
        out = []
        for key, value in attrs:
            if tag_name == "svg" and key in ROOT_ONLY_DROPS:
                continue
            if key in ATTR_RENAMES:
                if ATTR_RENAMES[key] is None:
                    continue
                key = ATTR_RENAMES[key]
            else:
                key = camel(key)
            if "{" in value or "}" in value:
                sys.exit(f"brace in attribute value: {key}={value}")
            out.append(f'{key}="{tidy_numbers(value)}"')
        if tag_name == "svg":
            out = [a for a in out if not a.startswith("className=")]
            out = root_extra + out
        joined = (" " + " ".join(out)) if out else ""
        return f"<{tag_name}{joined}{' /' if self_close else ''}>"

    svg = re.sub(r"<[^>]+>", tag, svg)
    return svg


def add_dash_mask(svg, route_d, width, height):
    mask = (f'<mask id="route-dash-mask" maskUnits="userSpaceOnUse" x="0" y="0" width="{width}" height="{height}">'
            f'<path id="route-dash-mask-path" d="{route_d}" fill="none" stroke="#fff" stroke-width="44" '
            f'stroke-linecap="butt" stroke-linejoin="round"/></mask>')
    if "<defs>" not in svg:
        sys.exit("no <defs> to hold the dash mask")
    svg = svg.replace("<defs>", "<defs>" + mask, 1)
    tags = re.findall(r'<path[^>]*\sid="route-dashes"[^>]*>', svg)
    if len(tags) != 1:
        sys.exit("route-dashes path not found exactly once")
    svg = svg.replace(tags[0], tags[0].replace("<path ", '<path mask="url(#route-dash-mask)" ', 1))
    return svg


def geometry(raw, key):
    vb = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', raw)
    width, height = float(vb.group(1)), float(vb.group(2))
    route_tag = re.search(r'<path[^>]*\sid="route-dashes"[^>]*>', raw).group(0)
    route_d = re.search(r'\sd="([^"]+)"', route_tag).group(1)
    trail_tag = re.search(r'<path[^>]*\sid="route-trail"[^>]*>', raw).group(0)
    if re.search(r'\sd="([^"]+)"', trail_tag).group(1) != route_d:
        sys.exit(f"{key}: route-trail and route-dashes differ")
    veh = re.search(r'<g id="vehicle" transform="translate\(([-\d.]+),([-\d.]+)\) scale\(([-\d.]+),([-\d.]+)\)', raw)
    car_scale = float(veh.group(3))
    stop_axle = (float(veh.group(1)), float(veh.group(2)))
    starts = []
    for n in (1, 2, 3):
        m = re.search(rf'<g id="stand-{n}-place" transform="translate\(([-\d.]+),([-\d.]+)\) scale\(([-\d.]+),([-\d.]+)\)', raw)
        starts.append((float(m.group(1)), float(m.group(2)), float(m.group(3))))
    mirrored = starts[0][2] < 0
    student_scale = abs(starts[0][2])
    if abs(student_scale - car_scale * STUDENT_SCALE_K) > 1e-6:
        sys.exit(f"{key}: student scale {student_scale} != car scale x {STUDENT_SCALE_K}")
    return dict(width=width, height=height, route=route_d, car_scale=car_scale, stop_axle=stop_axle,
                starts=[(x, y) for x, y, _ in starts], mirrored=mirrored, student_scale=student_scale)


def write(path, text):
    # Always LF and UTF-8, so regenerating on Windows produces byte-identical files.
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def ts_number(v):
    return f"{v:.4f}".rstrip("0").rstrip(".")


def main():
    if not os.path.isdir(ART):
        sys.exit("run from the repo root (design/intro-art/final/themed not found)")
    os.makedirs(OUT, exist_ok=True)
    geo_entries = []
    for key, comp in (("desktop", "DesktopScene"), ("mobile", "MobileScene")):
        raw = open(os.path.join(ART, f"iit-transit-final-frame-{key}.app.svg"), encoding="utf-8").read()
        g = geometry(raw, key)
        raw = add_dash_mask(raw, g["route"], ts_number(g["width"]), ts_number(g["height"]))
        root_extra = [
            'className={className ? `it-art ${className}` : "it-art"}',
            f'data-scene="{key}"',
            'preserveAspectRatio="xMidYMid meet"',
            'width="100%"',
            'height="100%"',
        ]
        jsx = svg_to_jsx(raw, root_extra)
        jsx = "\n".join("    " + line.rstrip() if line.strip() else "" for line in jsx.splitlines())
        tsx = (GENERATED_HEADER +
               f'import type {{ SVGProps }} from "react";\n\n'
               f'type Props = Pick<SVGProps<SVGSVGElement>, "className">;\n\n'
               f'// Final frame of the intro ({key}): the end of the story. The animation moves these\n'
               f'// elements by their ids; with no animation running, this is exactly the Motion OFF view.\n'
               f'export default function {comp}({{ className }}: Props) {{\n'
               f'  return (\n{jsx}\n  );\n}}\n')
        write(os.path.join(OUT, f"{comp}.tsx"), tsx)
        s = STORY[key]
        cap = s["captionBox"]
        geo_entries.append(f'''  {key}: {{
    key: "{key}",
    width: {ts_number(g["width"])},
    height: {ts_number(g["height"])},
    route: "{g["route"]}",
    carScale: {ts_number(g["car_scale"])},
    carAnchor: {{ x: {CAR_ANCHOR[0]}, y: {CAR_ANCHOR[1]} }},
    pickupFraction: {s["pickup"]},
    stopFraction: {s["stop"]},
    stopAxle: {{ x: {ts_number(g["stop_axle"][0])}, y: {ts_number(g["stop_axle"][1])} }},
    startFacing: {s["startFacing"]},
    studentScale: {ts_number(g["student_scale"])},
    studentsMirrored: {"true" if g["mirrored"] else "false"},
    studentStarts: [{", ".join(f"{{ x: {ts_number(x)}, y: {ts_number(y)} }}" for x, y in g["starts"])}],
    captionBox: {"null" if cap is None else f"{{ x: {cap[0]}, y: {cap[1]}, width: {cap[2]}, height: {cap[3]} }}"},
  }},''')
    geo = (GENERATED_HEADER + '''
export type SceneKey = "desktop" | "mobile";

export interface Point {
  x: number;
  y: number;
}

export interface SceneGeometry {
  key: SceneKey;
  /** Scene size in its own units (the SVG viewBox). */
  width: number;
  height: number;
  /** The route path (same d as #route-dashes and #route-trail). */
  route: string;
  /** Scale applied to the car's own units in this scene. */
  carScale: number;
  /** The car's axle point in its own units: the point placed on the route. */
  carAnchor: Point;
  /** Where the car waits for the students, as a share of the route length. */
  pickupFraction: number;
  /** Where the car stops at the end of the story, as a share of the route length. */
  stopFraction: number;
  /** The car's axle position in the final frame (must agree with stopFraction). */
  stopAxle: Point;
  /** 1 = the car faces right at pickup, -1 = mirrored to face left. */
  startFacing: 1 | -1;
  /** Scale of the standing students (car scale x 1.3). */
  studentScale: number;
  /** Mobile students walk left, so they are mirrored. */
  studentsMirrored: boolean;
  /** Feet position of each standing student at the start of the story. */
  studentStarts: [Point, Point, Point];
  /** Area kept free for the desktop caption, in scene units. Null where the caption sits outside the scene. */
  captionBox: { x: number; y: number; width: number; height: number } | null;
}

export const SCENES: Record<SceneKey, SceneGeometry> = {
''' + "\n".join(geo_entries) + "\n};\n")
    write(os.path.join(OUT, "sceneGeometry.ts"), geo)
    print("wrote", os.path.join(OUT, "DesktopScene.tsx"), os.path.join(OUT, "MobileScene.tsx"),
          os.path.join(OUT, "sceneGeometry.ts"))


if __name__ == "__main__":
    main()
